    private void loginKasirButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginKasirButtonActionPerformed
        // TODO add your handling code here:
        JPasswordField pf = new JPasswordField();
        int pilih = JOptionPane.showConfirmDialog(this, pf, "Password Kasir/Admin",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);

        if (pilih != JOptionPane.OK_OPTION) {
            return;
        }

        if (new String(pf.getPassword()).equals("admin123")) {
            FormKasir obj = new FormKasir();
            obj.setVisible(true);
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Password salah!", "Gagal", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_loginKasirButtonActionPerformed

