    // Isi tabel Makanan dan Minuman dari data controller.
    private void muatMenu() {
        isiTabelMenu(modelMakanan, kontrol.getDaftarMakanan());
        isiTabelMenu(modelMinuman, kontrol.getDaftarMinuman());
    }

    private void isiTabelMenu(DefaultTableModel model, Menu[] daftar) {
        model.setRowCount(0);
        for (int i = 0; i < daftar.length; i++) {
            String stok = (daftar[i].getStok() == 0) ? "Habis" : String.valueOf(daftar[i].getStok());
            model.addRow(new Object[] {
                i + 1,
                daftar[i].getNama(),
                kontrol.formatRupiah(daftar[i].getHarga()),
                stok
            });
        }
    }

    // Isi tabel keranjang dan label total.
    private void tampilkanKeranjang() {
        arrayPesanan k = kontrol.getKeranjang();
        modelKeranjang.setRowCount(0);

        for (int i = 0; i < k.getJumlahItem(); i++) {
            ItemPesanan item = k.getItem(i);
            modelKeranjang.addRow(new Object[] {
                i + 1,
                item.getMenu().getNama(),
                kontrol.formatRupiah(item.getMenu().getHarga()),
                item.getJumlah(),
                kontrol.formatRupiah(item.getSubtotal())
            });
        }

        ttlLabel.setText(kontrol.formatRupiah(k.getTotal()));
    }
    
    private void tambahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahButtonActionPerformed
        // TODO add your handling code here:
        int kategori = menu.getSelectedIndex() + 1;   // 1 = Makanan, 2 = Minuman
        javax.swing.JTable tabel = (kategori == 1) ? makananTabel : minumanTabel;
        int nomor = tabel.getSelectedRow() + 1;       // 0 kalau belum dipilih
        int jumlah = (Integer) jumlahSpinner.getValue();

        String hasil = kontrol.tambahKeKeranjang(kategori, nomor, jumlah);

        if (hasil.equals("OK")) {
            tampilkanKeranjang();
            jumlahSpinner.setValue(1);
        } else {
            JOptionPane.showMessageDialog(this, hasil, "Perhatian", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_tambahButtonActionPerformed

    private void kosongkanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_kosongkanButtonActionPerformed
        // TODO add your handling code here:
        if (kontrol.getKeranjang().getJumlahItem() == 0) {
            return;
        }

        int pilih = JOptionPane.showConfirmDialog(this, "Kosongkan semua pesanan?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (pilih == JOptionPane.YES_OPTION) {
            kontrol.kosongkanKeranjang();
            tampilkanKeranjang();
        }
    }//GEN-LAST:event_kosongkanButtonActionPerformed

    private void bayarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bayarButtonActionPerformed
        // TODO add your handling code here:
        if (kontrol.getKeranjang().getJumlahItem() == 0) {
            JOptionPane.showMessageDialog(this, "Belum ada pesanan.", "Perhatian", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 1. Data pelanggan
        String nama = JOptionPane.showInputDialog(this, "Nama pelanggan:");
        if (nama == null) {
            return; // Cancel
        }

        String meja = JOptionPane.showInputDialog(this, "Nomor meja:");
        if (meja == null) {
            return;
        }
        if (meja.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nomor meja harus diisi!", "Perhatian", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Pilih metode pembayaran
        String[] pilihan = {"Bank Account", "E-Wallet", "QRIS"};
        int pilih = JOptionPane.showOptionDialog(this,
                "Total bayar: " + kontrol.formatRupiah(kontrol.getKeranjang().getTotal())
                + "\nPilih metode pembayaran:",
                "Pembayaran", JOptionPane.DEFAULT_OPTION, JOptionPane.QUESTION_MESSAGE,
                null, pilihan, pilihan[0]);

        if (pilih < 0) {
            return; // dialog ditutup
        }

        // 3. Data sesuai metode
        String metode = "QRIS";
        String noRekHp = "";
        String kode = "";

        if (pilih == 0) {
            metode = "BANK";
            noRekHp = JOptionPane.showInputDialog(this, "Nomor rekening (angka):");
            if (noRekHp == null) {
                return;
            }
            kode = JOptionPane.showInputDialog(this, "Security code (3 karakter):");
            if (kode == null) {
                return;
            }
        } else if (pilih == 1) {
            metode = "EWALLET";
            noRekHp = JOptionPane.showInputDialog(this, "Nomor HP (10 digit):");
            if (noRekHp == null) {
                return;
            }
        }

        // 4. Proses oleh controller
        String hasil = kontrol.prosesPembayaran(nama, meja, metode, noRekHp, kode);

        if (hasil.startsWith("GAGAL")) {
            JOptionPane.showMessageDialog(this, hasil, "Gagal", JOptionPane.ERROR_MESSAGE);
        } else {
            javax.swing.JTextArea area = new javax.swing.JTextArea(hasil);
            area.setFont(new java.awt.Font(java.awt.Font.MONOSPACED, java.awt.Font.PLAIN, 13));
            area.setEditable(false);

            javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(area);
            scroll.setPreferredSize(new java.awt.Dimension(420, 320));

            JOptionPane.showMessageDialog(this, scroll, "Pembayaran Berhasil", JOptionPane.INFORMATION_MESSAGE);

            tampilkanKeranjang();   // keranjang jadi kosong
            muatMenu();             // stok di tabel ikut berkurang
        }
    }//GEN-LAST:event_bayarButtonActionPerformed

