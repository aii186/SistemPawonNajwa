    // Isi tabel Makanan dan Minuman dari data controller.
    private void muatMenu() {
        isiTabelMenu(modelMakanan, kontrol.getDaftarMakanan());
        isiTabelMenu(modelMinuman, kontrol.getDaftarMinuman());
    }

    private void isiTabelMenu(DefaultTableModel model, Menu[] daftar) {
        model.setRowCount(0);
        for (int i = 0; i < daftar.length; i++) {
            model.addRow(new Object[] {
                i + 1,
                daftar[i].getNama(),
                kontrol.formatRupiah(daftar[i].getHarga()),
                "Edit",
                daftar[i].getStok()
            });
        }
    }

    private void setKolomEdit(javax.swing.JTable tabel) {
        javax.swing.table.TableCellRenderer renderer = (table, value, selected, focus, row, column) -> {
            javax.swing.JButton button = new javax.swing.JButton("Edit");
            button.setFont(new java.awt.Font("Perpetua", java.awt.Font.BOLD, 13));
            button.setMargin(new java.awt.Insets(1, 4, 1, 4));
            return button;
        };
        tabel.getColumnModel().getColumn(3).setCellRenderer(renderer);
        tabel.getColumnModel().getColumn(3).setPreferredWidth(65);
        tabel.getColumnModel().getColumn(3).setMaxWidth(70);
        tabel.getColumnModel().getColumn(4).setPreferredWidth(45);
        tabel.getColumnModel().getColumn(4).setMaxWidth(55);
        tabel.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override public void mouseClicked(java.awt.event.MouseEvent e) {
                int column = tabel.columnAtPoint(e.getPoint());
                if (column >= 0 && tabel.convertColumnIndexToModel(column) == 3) editMenu();
            }
        });
    }

    // Isi tabel keranjang dan label total.
    private void tampilkanKeranjang() {
        int dipilih = keranjangTabel.getSelectedRow();
        modelKeranjang.setRowCount(0);
        java.util.List<model.TransaksiPesanan> transaksi = kontrol.getDaftarTransaksi();
        for (model.TransaksiPesanan item : transaksi) {
            modelKeranjang.addRow(new Object[] {
                item.getIdTransaksi(),
                item.getNamaPelanggan() + " / Meja " + item.getNomorMeja(),
                item.getRingkasanItem(),
                kontrol.formatRupiah(item.getTotal()),
                item.getStatus()
            });
        }
        if (dipilih >= 0 && dipilih < modelKeranjang.getRowCount()) {
            keranjangTabel.setRowSelectionInterval(dipilih, dipilih);
        }
        ttlLabel.setText(kontrol.formatRupiah(kontrol.getTotalPendapatan()));
    }

    private Menu menuTerseleksi() {
        javax.swing.JTable tabel = menu.getSelectedIndex() == 0 ? makananTabel : minumanTabel;
        int baris = tabel.getSelectedRow();
        if (baris < 0) return null;
        Menu[] daftar = menu.getSelectedIndex() == 0 ? kontrol.getDaftarMakanan() : kontrol.getDaftarMinuman();
        baris = tabel.convertRowIndexToModel(baris);
        return baris < daftar.length ? daftar[baris] : null;
    }

    private int indexMenu(Menu target) {
        Menu[] semua = kontrol.getSemuaMenu();
        for (int i = 0; i < semua.length; i++) if (semua[i] == target) return i;
        return -1;
    }

    private void tambahMenu() {
        javax.swing.JComboBox<String> kategori = new javax.swing.JComboBox<>(new String[]{"Makanan", "Minuman"});
        javax.swing.JTextField nama = new javax.swing.JTextField();
        javax.swing.JTextField harga = new javax.swing.JTextField();
        javax.swing.JTextField stok = new javax.swing.JTextField("0");
        Object[] form = {"Kategori", kategori, "Nama menu", nama, "Harga (angka)", harga, "Stok awal", stok};
        if (JOptionPane.showConfirmDialog(this, form, "Tambah Menu", JOptionPane.OK_CANCEL_OPTION) != JOptionPane.OK_OPTION) return;
        try {
            String hasil = kontrol.tambahMenuBaru((String) kategori.getSelectedItem(), nama.getText(),
                    Integer.parseInt(harga.getText().trim()), Integer.parseInt(stok.getText().trim()));
            if (!"OK".equals(hasil)) JOptionPane.showMessageDialog(this, hasil, "Perhatian", JOptionPane.WARNING_MESSAGE);
            muatMenu();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Harga dan stok harus berupa angka.", "Perhatian", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void editMenu() {
        Menu item = menuTerseleksi();
        if (item == null) {
            JOptionPane.showMessageDialog(this, "Pilih menu yang ingin diedit.", "Perhatian", JOptionPane.WARNING_MESSAGE);
            return;
        }
        javax.swing.JTextField nama = new javax.swing.JTextField(item.getNama());
        javax.swing.JTextField harga = new javax.swing.JTextField(String.valueOf(item.getHarga()));
        javax.swing.JTextField stok = new javax.swing.JTextField(String.valueOf(item.getStok()));
        Object[] form = {"Nama menu", nama, "Harga", harga, "Stok", stok};
        if (JOptionPane.showConfirmDialog(this, form, "Edit Menu", JOptionPane.OK_CANCEL_OPTION) != JOptionPane.OK_OPTION) return;
        try {
            String hasil = kontrol.ubahMenu(indexMenu(item), nama.getText(), Integer.parseInt(harga.getText().trim()), Integer.parseInt(stok.getText().trim()));
            if (!"OK".equals(hasil)) JOptionPane.showMessageDialog(this, hasil, "Perhatian", JOptionPane.WARNING_MESSAGE);
            muatMenu();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Harga dan stok harus berupa angka.", "Perhatian", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void hapusMenu() {
        Menu item = menuTerseleksi();
        if (item == null) {
            JOptionPane.showMessageDialog(this, "Pilih menu yang ingin dihapus.", "Perhatian", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int pilih = JOptionPane.showConfirmDialog(this, "Hapus menu " + item.getNama() + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (pilih == JOptionPane.YES_OPTION) {
            String hasil = kontrol.hapusMenu(indexMenu(item));
            if (!"OK".equals(hasil)) JOptionPane.showMessageDialog(this, hasil, "Perhatian", JOptionPane.WARNING_MESSAGE);
            muatMenu();
        }
    }

    private void ubahStatusPesanan(String status) {
        int baris = keranjangTabel.getSelectedRow();
        if (baris < 0) {
            JOptionPane.showMessageDialog(this, "Pilih pesanan yang ingin diperbarui.", "Perhatian", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String hasil = kontrol.ubahStatusPesanan(keranjangTabel.convertRowIndexToModel(baris), status);
        if (!"OK".equals(hasil)) JOptionPane.showMessageDialog(this, hasil, "Perhatian", JOptionPane.WARNING_MESSAGE);
        tampilkanKeranjang();
    }

    private void pasangAksiKonteks() {
        javax.swing.JPopupMenu popupMenu = new javax.swing.JPopupMenu();
        javax.swing.JMenuItem edit = new javax.swing.JMenuItem("Edit Menu");
        javax.swing.JMenuItem hapus = new javax.swing.JMenuItem("Hapus Menu");
        edit.addActionListener(e -> editMenu());
        hapus.addActionListener(e -> hapusMenu());
        popupMenu.add(edit);
        popupMenu.add(hapus);
        makananTabel.setComponentPopupMenu(popupMenu);
        minumanTabel.setComponentPopupMenu(popupMenu);
        javax.swing.JPopupMenu popupPesanan = new javax.swing.JPopupMenu();
        tambahAksiStatus(popupPesanan, "Terima Pesanan", "Diterima");
        tambahAksiStatus(popupPesanan, "Proses Pesanan", "Diproses");
        tambahAksiStatus(popupPesanan, "Tandai Selesai", "Selesai");
        tambahAksiStatus(popupPesanan, "Batalkan Pesanan", "Dibatalkan");
        keranjangTabel.setComponentPopupMenu(popupPesanan);
        java.awt.event.MouseAdapter pilihBaris = new java.awt.event.MouseAdapter() {
            private void pilih(javax.swing.JTable tabel, java.awt.event.MouseEvent e) {
                if (e.isPopupTrigger()) {
                    int baris = tabel.rowAtPoint(e.getPoint());
                    if (baris >= 0) tabel.setRowSelectionInterval(baris, baris);
                }
            }
            @Override public void mousePressed(java.awt.event.MouseEvent e) { pilih((javax.swing.JTable)e.getComponent(), e); }
            @Override public void mouseReleased(java.awt.event.MouseEvent e) { pilih((javax.swing.JTable)e.getComponent(), e); }
        };
        makananTabel.addMouseListener(pilihBaris);
        minumanTabel.addMouseListener(pilihBaris);
        keranjangTabel.addMouseListener(pilihBaris);
        makananTabel.addMouseListener(new java.awt.event.MouseAdapter() { @Override public void mouseClicked(java.awt.event.MouseEvent e) { if (e.getClickCount() == 2) editMenu(); } });
        minumanTabel.addMouseListener(new java.awt.event.MouseAdapter() { @Override public void mouseClicked(java.awt.event.MouseEvent e) { if (e.getClickCount() == 2) editMenu(); } });
    }

